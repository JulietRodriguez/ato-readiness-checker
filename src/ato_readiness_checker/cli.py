"""Command-line interface.

Exit codes: 0 = reviewed and the gate passed, 1 = the --fail-on / --min-score
gate failed, 2 = bad arguments or an input could not be loaded.
"""

from __future__ import annotations

import argparse
import contextlib
import json
import sys
from datetime import date
from pathlib import Path

from ato_readiness_checker import __version__
from ato_readiness_checker.baseline import load_baseline
from ato_readiness_checker.checks import check_catalog
from ato_readiness_checker.loader import LoadError, load_package
from ato_readiness_checker.model import Severity
from ato_readiness_checker.reports import (
    brief_html,
    brief_markdown,
    report_html,
    report_json,
    report_markdown,
    review_to_oscal,
)
from ato_readiness_checker.review import DISCLAIMER, Review, run_review
from ato_readiness_checker.schema import SchemaUnavailable
from ato_readiness_checker.scoring import gate_failed

FORMATS = ("md", "html", "json")


def _date(value: str) -> date:
    try:
        return date.fromisoformat(value)
    except ValueError as exc:
        raise argparse.ArgumentTypeError(f"not a YYYY-MM-DD date: {value!r}") from exc


def _fail_on(value: str) -> Severity | None:
    if value.lower() == "none":
        return None
    try:
        return Severity.parse(value)
    except ValueError as exc:
        raise argparse.ArgumentTypeError(str(exc)) from exc


def _formats(value: str) -> list[str]:
    chosen = [v.strip().lower() for v in value.split(",") if v.strip()]
    bad = [v for v in chosen if v not in FORMATS]
    if bad or not chosen:
        raise argparse.ArgumentTypeError(f"formats must be from {', '.join(FORMATS)}")
    return chosen


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog="ato-readiness-checker",
        description="Review an OSCAL authorization package (SSP, Assessment Results, POA&M) before it goes to the AO.",
    )
    parser.add_argument("--version", action="version", version=f"%(prog)s {__version__}")
    sub = parser.add_subparsers(dest="command", required=True)

    chk = sub.add_parser("check", help="review a package and write reports")
    chk.add_argument("--ssp", help="OSCAL SSP (JSON)")
    chk.add_argument("--ar", action="append", default=[], help="OSCAL Assessment Results (JSON); repeatable")
    chk.add_argument("--poam", action="append", default=[], help="OSCAL POA&M (JSON); repeatable")
    chk.add_argument("--baseline", help="baseline: OSCAL profile or catalog (JSON), JSON list, or text list")
    chk.add_argument("--as-of", type=_date, help="date to judge due dates against (default: today, UTC)")
    chk.add_argument(
        "--max-assessment-age", type=int, default=365, metavar="DAYS", help="oldest acceptable assessment (default 365)"
    )
    chk.add_argument("--schema-dir", help="directory holding NIST's OSCAL 1.1.2 JSON schemas (enables REF-006)")
    chk.add_argument("-o", "--out-dir", help="write reports here (created if missing)")
    chk.add_argument(
        "--format", type=_formats, default=list(FORMATS), help="report formats, comma-separated (default md,html,json)"
    )
    chk.add_argument("--brief", action="store_true", help="also write the draft AO decision brief (md + html)")
    chk.add_argument("--oscal", action="store_true", help="also write the review as OSCAL 1.1.2 Assessment Results")
    chk.add_argument(
        "--fail-on",
        type=_fail_on,
        default=None,
        metavar="SEVERITY",
        help="exit 1 if any issue is at or above this severity: critical, high, medium, low, info, none (default none)",
    )
    chk.add_argument("--min-score", type=float, help="exit 1 if the readiness score is below this")
    chk.add_argument("--generated-at", help=argparse.SUPPRESS)  # fixed timestamp for reproducible samples
    chk.add_argument("-q", "--quiet", action="store_true", help="print only the one-line result")

    lst = sub.add_parser("list-checks", help="list every check")
    lst.add_argument("--markdown", action="store_true", help="print as the Markdown table used in docs/checks.md")
    return parser


def checks_markdown() -> str:
    lines = [
        "# Readiness checks",
        "",
        "Generated by `ato-readiness-checker list-checks --markdown`. CI fails if this file is out of date.",
        "",
        "Severity is how much a failed check matters for the package (the tool's own scale). "
        "Some checks raise or lower the severity of individual issues; the check description says when.",
        "",
        "| ID | Check | Category | Severity | What it looks for |",
        "|---|---|---|---|---|",
    ]
    for c in check_catalog():
        lines.append(f"| {c.check_id} | {c.title} | {c.category} | {c.severity.value} | {c.description} |")
    return "\n".join(lines) + "\n"


def _summary(review: Review) -> str:
    d = review.to_dict()
    counts, risk = d["issue_counts"], d["risk_issue_counts"]
    return (
        f"{review.level}: readiness score {review.score}/100 for {review.system_name}\n"
        f"  package issues: critical {counts['critical']}, high {counts['high']}, medium {counts['medium']}, "
        f"low {counts['low']}\n"
        f"  risk items for the AO: critical {risk['critical']}, high {risk['high']}, accepted {risk['info']}"
    )


def _write_outputs(review: Review, args: argparse.Namespace) -> list[Path]:
    out = Path(args.out_dir)
    out.mkdir(parents=True, exist_ok=True)
    written = []
    renderers = {"md": report_markdown, "html": report_html, "json": report_json}
    for fmt in args.format:
        path = out / f"readiness-report.{fmt}"
        path.write_text(renderers[fmt](review), encoding="utf-8")
        written.append(path)
    if args.brief:
        for name, render in (("ao-brief-draft.md", brief_markdown), ("ao-brief-draft.html", brief_html)):
            path = out / name
            path.write_text(render(review), encoding="utf-8")
            written.append(path)
    if args.oscal:
        path = out / "readiness-review.oscal.json"
        path.write_text(json.dumps(review_to_oscal(review), indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
        written.append(path)
    return written


def _cmd_check(args: argparse.Namespace) -> int:
    if not (args.ssp or args.ar or args.poam):
        print("error: give at least one of --ssp, --ar, --poam", file=sys.stderr)
        return 2
    try:
        package = load_package(args.ssp, args.ar, args.poam)
        baseline = load_baseline(args.baseline) if args.baseline else None
        review = run_review(
            package,
            baseline=baseline,
            as_of=args.as_of,
            max_assessment_age_days=args.max_assessment_age,
            schema_dir=args.schema_dir,
            generated_at=args.generated_at,
        )
    except (LoadError, SchemaUnavailable) as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 2

    print(_summary(review))
    if not args.quiet:
        for issue in review.issues:
            if issue.severity in (Severity.CRITICAL, Severity.HIGH):
                ref = f" [{issue.ref}]" if issue.ref else ""
                print(f"  {issue.severity.value.upper():8} {issue.check_id}{ref}: {issue.message}")
        print(f"\n{DISCLAIMER}")
    if args.out_dir:
        for path in _write_outputs(review, args):
            if not args.quiet:
                print(f"wrote {path}")

    failed = gate_failed(review.results, args.fail_on)
    if args.min_score is not None and review.score < args.min_score:
        print(f"gate: score {review.score} is below --min-score {args.min_score}", file=sys.stderr)
        failed = True
    if failed and args.fail_on is not None and gate_failed(review.results, args.fail_on):
        print(f"gate: found issues at or above '{args.fail_on.value}'", file=sys.stderr)
    return 1 if failed else 0


def main(argv: list[str] | None = None) -> int:
    for stream in (sys.stdout, sys.stderr):
        if hasattr(stream, "reconfigure"):
            with contextlib.suppress(ValueError, OSError):
                stream.reconfigure(encoding="utf-8")
    args = build_parser().parse_args(argv)
    if args.command == "list-checks":
        if args.markdown:
            sys.stdout.write(checks_markdown())
        else:
            for c in check_catalog():
                print(f"{c.check_id:9} {c.severity.value:8} {c.title}")
        return 0
    return _cmd_check(args)


if __name__ == "__main__":  # pragma: no cover
    raise SystemExit(main())
